CREATE TABLE IF NOT EXISTS lab1_coordinates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    x BIGINT NOT NULL CHECK (x <= 509),
    y BIGINT NOT NULL CHECK (y > -897)
);

CREATE TABLE IF NOT EXISTS lab1_location (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    x REAL NOT NULL CHECK (x > '-Infinity'::real AND x < 'Infinity'::real),
    y DOUBLE PRECISION NOT NULL CHECK (y > '-Infinity'::double precision AND y < 'Infinity'::double precision),
    z DOUBLE PRECISION NOT NULL CHECK (z > '-Infinity'::double precision AND z < 'Infinity'::double precision),
    name VARCHAR(345) NOT NULL
);

CREATE TABLE IF NOT EXISTS lab1_route (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    coordinates_id INTEGER NOT NULL REFERENCES lab1_coordinates(id) ON DELETE CASCADE,
    creation_date DATE NOT NULL DEFAULT CURRENT_DATE,
    from_id INTEGER NOT NULL REFERENCES lab1_location(id) ON DELETE CASCADE,
    to_id INTEGER REFERENCES lab1_location(id) ON DELETE CASCADE,
    distance BIGINT CHECK (distance > 1),
    rating INTEGER NOT NULL CHECK (rating > 0),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS lab1_route_rating_idx ON lab1_route(rating);
CREATE INDEX IF NOT EXISTS lab1_route_locations_idx ON lab1_route(from_id, to_id);
CREATE INDEX IF NOT EXISTS lab1_route_coordinates_idx ON lab1_route(coordinates_id);
